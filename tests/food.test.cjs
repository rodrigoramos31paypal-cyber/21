const assert=require('node:assert/strict');
const vm=require('node:vm'),fs=require('node:fs'),path=require('node:path');
const F=require('../alimentacao.js');
const scope={window:{}};vm.runInNewContext(fs.readFileSync(path.join(__dirname,'../receitas.js'),'utf8'),scope);
const R=JSON.parse(JSON.stringify(scope.window.FOCO_RECIPES));
const p={goal:'manter',diet:'todos',allergies:[],meals:Object.keys(F.meals)};
const plan=F.createPlan(R,p);assert.equal(plan.length,21);
assert.ok(plan.every(day=>Object.keys(day).length===4));
for(const day of plan)for(const [meal,id] of Object.entries(day))assert.ok(F.compatible(R.find(r=>r.id===id),p,meal));
const vegan={...p,diet:'vegan',allergies:['amendoim']};
const vp=F.createPlan(R,vegan);assert.ok(vp.every(day=>day.pequeno===null&&day.lanche===null));
assert.ok(vp.every(day=>day.almoco==='marmita-vegetal'));
assert.ok(F.createPlan(R,{...p,otherRestrictions:'Ingrediente por rever'}).every(day=>Object.values(day).every(id=>id===null)));
const milkFree={...p,allergies:['leite']};assert.ok(F.candidates(R,milkFree,'pequeno').every(r=>!r.allergens.includes('leite')));
const repeat=Array.from({length:21},()=>({almoco:'marmita-base',jantar:'marmita-base'}));
const list=F.shopping(R,repeat,0);const chicken=list.find(i=>i.name==='peito de frango');
assert.equal(chicken.qty,2100);assert.equal(chicken.maximum,2520);assert.equal(chicken.count,14);
assert.equal(list.find(i=>i.name==='arroz basmati cru').qty,980);
const changed=JSON.parse(JSON.stringify(repeat));changed[0].almoco='marmita-vegetal';
assert.equal(F.shopping(R,changed,0).find(i=>i.name==='peito de frango').qty,1950);
assert.equal(F.shopping(R,changed,1).find(i=>i.name==='peito de frango').qty,2100);
assert.ok(R.every(r=>fs.existsSync(path.join(__dirname,'..',r.image))));
console.log('Plano 21 dias, restrições, lacunas, compras agregadas, trocas e imagens: OK');
